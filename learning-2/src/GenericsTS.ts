// here A & B is the datatypes of a, b
// tuple is used here to return multiple types of values
function pair<A, B> ( a: A, b: B ) : [A, B] {
    return [a, b]
}

console.log("pair => ", pair(1, "hello"))
console.log("pair => ", pair("Masala", "Chai"))
console.log("pair => ", pair({a: 1}, {b: 2}))



