// --- Built-in Generic Utility Types: Partial, Required, Pick, Omit ---

// Base Interface for our example
interface ChaiOrder {
    id: number;
    flavor: string;
    price: number;
    sugar?: boolean; // Optional property
}

// 1. Partial<T> -> Makes ALL properties OPTIONAL (?)
// Useful when updating an existing order where you only send changed fields
const updateOrder: Partial<ChaiOrder> = {
    flavor: "Ginger" // id, price, and sugar are not required
};
console.log("Partial (updateOrder) =>", updateOrder);


// 2. Required<T> -> Makes ALL properties MANDATORY (removes ?)
// Even 'sugar' which was optional is now strictly required
const completeOrder: Required<ChaiOrder> = {
    id: 1,
    flavor: "Masala",
    price: 30,
    sugar: true // Must provide sugar!
};
console.log("Required (completeOrder) =>", completeOrder);


// 3. Pick<T, Keys> -> Selects ONLY the specified keys from T
// Useful when you need a smaller slice of an object (e.g. summary display)
type OrderSummary = Pick<ChaiOrder, "flavor" | "price">;

const summary: OrderSummary = {
    flavor: "Elaichi",
    price: 40
};
console.log("Pick (summary) =>", summary);


// 4. Omit<T, Keys> -> REMOVES specific keys and keeps everything else
// Useful for creating a new order before an 'id' is generated by the database
type NewChaiOrder = Omit<ChaiOrder, "id">;

const newOrder: NewChaiOrder = {
    flavor: "Kesar",
    price: 60,
    sugar: false
};
console.log("Omit (newOrder) =>", newOrder);


