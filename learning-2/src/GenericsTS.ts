// function overloading


// here we are using 'any' type
function printValues(arg1: any, arg2: any): void {
    console.log(arg1, arg2);
}

printValues(10, "Hello");        // 10, Hello
printValues("Type", true);          // Type, true
printValues(3.14, [1, 2]);      // 3.14, [1, 2]
