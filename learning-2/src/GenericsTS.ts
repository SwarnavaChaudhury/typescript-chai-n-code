
// --- Generics in TypeScript ---
// Generics allow you to create reusable components that work with ANY type 
// while still retaining full TYPE SAFETY (unlike using 'any').

// <T> is a "Type Variable" (placeholder) that captures the type passed in.
// - Parameter 'item: T' accepts a value of type T
// - Return type 'T[]' guarantees an array containing elements of that exact same type T
function wrapInArray<T>(item: T): T[] {
    return [item];
}

// 1. Passing a string -> TypeScript automatically infers T as string -> returns string[]
const stringArray = wrapInArray("Generics function define here");
console.log("stringArray =>", stringArray);

// 2. Passing a number -> TypeScript automatically infers T as number -> returns number[]
const numberArray = wrapInArray(43);
console.log("numberArray =>", numberArray);

// 3. Passing an object -> TypeScript infers T as { flavor: string, price: number } -> returns object[]
const objectArray = wrapInArray({ flavor: "Ginger", price: 50 });
console.log("objectArray =>", objectArray);

// 4. You can also explicitly specify the type if needed:
const explicitArray = wrapInArray<string>("Explicit type string");
console.log("explicitArray =>", explicitArray);









