// real world example
// api usages
interface ApiPromise<T> {
    status: number
    data: T
    success: boolean
}

const res : ApiPromise< { flavor: string } > = {
    status: 200,
    data: {flavor: "Masala"},
    success: true
}

console.log("res => ", res)

const apiResult: ApiPromise<string> = {
    status: 200,
    data: "Hello",
    success: true
}

console.log("apiResult => ", apiResult)

const apiResult2: ApiPromise<{ name: string, age: number }> = {
    status: 200,
    data: { name: "John Doe", age: 30 },
    success: true
}

console.log("apiResult2 => ", apiResult2)

